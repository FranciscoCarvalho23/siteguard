"""Download the Construction-PPE dataset and build a reproducible train/val/test split.

The public dataset ships only train (800) and val (200). Tuning hyper-parameters
or picking the best epoch on the same images used for the final score inflates
the result, so we:

* hold out 100 of the original *train* images as our **val** set (model selection),
* keep the original 200 *val* images as an untouched **test** set (final report).

    python scripts/prepare_data.py            # -> configs/ppe.yaml + split lists in data/
"""

from __future__ import annotations

import argparse
import random
import sys
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URL = "https://github.com/ultralytics/assets/releases/download/v0.0.0/construction-ppe.zip"
NAMES = [
    "helmet",
    "gloves",
    "vest",
    "boots",
    "goggles",
    "Person",
    "no_helmet",
    "no_goggle",
    "no_gloves",
    "no_boots",
    "forklift",
    "no_vest",
]


def download(dest_dir: Path) -> Path:
    root = dest_dir / "construction-ppe"
    if (root / "images" / "train").exists():
        return root
    dest_dir.mkdir(parents=True, exist_ok=True)
    zpath = dest_dir / "construction-ppe.zip"
    if not zpath.exists():
        print(f"Downloading {URL} (~650 MB) ...")
        urllib.request.urlretrieve(URL, zpath)
    print("Extracting ...")
    with zipfile.ZipFile(zpath) as zf:
        zf.extractall(dest_dir)
    return root


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--datasets-dir", default=str(ROOT / "datasets"))
    ap.add_argument("--val-size", type=int, default=100)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    root = download(Path(args.datasets_dir)).resolve()
    train_imgs = sorted((root / "images" / "train").glob("*.jpg"))
    test_imgs = sorted((root / "images" / "val").glob("*.jpg"))
    rng = random.Random(args.seed)
    shuffled = train_imgs[:]
    rng.shuffle(shuffled)
    val_imgs = sorted(shuffled[: args.val_size])
    train_imgs = sorted(shuffled[args.val_size :])

    out = ROOT / "data"
    out.mkdir(exist_ok=True)
    for name, imgs in (("train", train_imgs), ("val", val_imgs), ("test", test_imgs)):
        (out / f"{name}.txt").write_text("\n".join(str(p) for p in imgs) + "\n")
        print(f"{name:5s} {len(imgs):4d} images")

    yaml = [
        "# Generated by scripts/prepare_data.py",
        f"path: {out}",
        "train: train.txt",
        "val: val.txt",
        "test: test.txt",
        "names:",
    ]
    yaml += [f"  {i}: {n}" for i, n in enumerate(NAMES)]
    (ROOT / "configs" / "ppe.yaml").write_text("\n".join(yaml) + "\n")
    print(f"Wrote {ROOT / 'configs' / 'ppe.yaml'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
